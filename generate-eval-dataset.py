#!/usr/bin/env python3
import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any, Dict

import boto3
from chat import run_conversation


def invoke_flow_once(
    client,
    flow_identifier: str,
    flow_alias_identifier: str,
    input_node_name: str,
    prompt: str,
    enable_trace: bool = False,
) -> Dict[str, Any]:
    """
    Invokes a Bedrock Flow and returns:
      {
        "executionId": "...",
        "final_output_text": "...",
        "final_output_raw": <document>,
        "trace": <optional list of trace events>
      }
    """
    resp = client.invoke_flow(
        flowIdentifier=flow_identifier,
        flowAliasIdentifier=flow_alias_identifier,
        enableTrace=enable_trace,
        inputs=[
            {
                "nodeName": input_node_name,
                "nodeOutputName": "document",
                "content": {"document": prompt},
            }
        ],
    )

    last_text_any = None

    for event in resp["responseStream"]:
        print("EVENT: " + str(event))
        if "flowOutputEvent" in event:
            oe = event["flowOutputEvent"]
            last_text_any = oe.get("content", {}).get("document")
            break

        if "flowMultiTurnInputRequestEvent" in event:
            ce = event["flowMultiTurnInputRequestEvent"]
            last_text_any = ce.get("content", {}).get("document")
            break

    return {
        "final_output_text": last_text_any,
    }


def main():
    p = argparse.ArgumentParser(description="Run Bedrock Flow tests and emit Bedrock Evaluations JSONL (LLM-as-judge BYOI).")
    p.add_argument("--tests-json", required=True, help="Path to the test suite JSON (the file from section 1).")
    p.add_argument("--flow-id", help="Bedrock Flow identifier (required for Flow mode).")
    p.add_argument("--flow-alias-id", help="Bedrock Flow alias identifier (required for Flow mode).")
    p.add_argument("--model-identifier", default="my-flow-app", help="Value to put in modelResponses[0].modelIdentifier.")
    p.add_argument("--out-jsonl", default="output_eval_dataset.jsonl", help="Where to write the eval dataset JSONL.")
    p.add_argument("--region", default=None, help="AWS region (optional; otherwise uses default boto config).")
    p.add_argument("--enable-trace", action="store_true", help="Include trace collection (not written to eval JSONL).")
    p.add_argument("--harness-tests", action="store_true", help="Run tests against the local AgentCore harness instead of a Bedrock Flow.")
    p.add_argument("--system-prompt", default=".harness/system_prompt.txt", help="Expanded harness prompt generated by create_harness.py.")
    p.add_argument("--gateway-url", default=None, help="AgentCore Gateway MCP URL.")
    p.add_argument("--harness-model-id", default="amazon.nova-pro-v1:0", help="Bedrock model ID used for harness tests.")
    args = p.parse_args()

    if not args.harness_tests and (not args.flow_id or not args.flow_alias_id):
        p.error("--flow-id and --flow-alias-id are required unless --harness-tests is used")

    suite = json.loads(Path(args.tests_json).read_text(encoding="utf-8"))
    input_node_name = suite.get("flowInputNode", {}).get("nodeName")

    if input_node_name:
        print("Input node name: " + input_node_name)

    tests = suite["tests"]

    session = boto3.Session(region_name=args.region) if args.region else boto3.Session()
    client = session.client("bedrock-runtime") if args.harness_tests else session.client("bedrock-agent-runtime")
    if args.harness_tests:
        system_prompt = Path(args.system_prompt).read_text(encoding="utf-8")
        gateway_url = args.gateway_url or os.getenv("AGENTCORE_GATEWAY_URL")
        if not gateway_url:
            raise ValueError("Set --gateway-url or AGENTCORE_GATEWAY_URL for harness tests")

    out_path = Path(args.out_jsonl)
    n_ok = 0

    with out_path.open("w", encoding="utf-8") as f:
        for t in tests:
            test_id = t["id"]
            reference = t.get("expected", "")
            prompt = t.get("prompt", "")
            turns = t.get("turns", [prompt])

            try:
                if args.harness_tests:
                    response_text = run_conversation(client, turns, system_prompt, gateway_url, args.harness_model_id)
                else:
                    result = invoke_flow_once(client=client, flow_identifier=args.flow_id, flow_alias_identifier=args.flow_alias_id, input_node_name=input_node_name, prompt=prompt, enable_trace=args.enable_trace)
                    response_text = result["final_output_text"]
                n_ok += 1
            except Exception as e:
                # If the Flow errors, still emit a record so the eval run captures failures
                print(e)
                response_text = f"[HARNESS_ERROR] {type(e).__name__}: {e}" if args.harness_tests else f"[FLOW_ERROR] {type(e).__name__}: {e}"

            # Bedrock Evaluations LLM-as-a-judge (BYOI) input JSONL record
            record = {
                "prompt": prompt,
                "referenceResponse": reference,
                "modelResponses": [
                    {
                        "response": response_text,
                        "modelIdentifier": args.model_identifier,
                    }
                ],
                # Optional: keep the test id as metadata by embedding into the prompt or category,
                # since the public schema doesn't show a dedicated id field.
            }

            f.write(json.dumps(record, ensure_ascii=False) + "\n")

            print(f"{test_id}: wrote eval line", file=sys.stderr)

    mode = "harness" if args.harness_tests else "flow"
    print(f"\nWrote {len(tests)} JSONL lines to {out_path} ({n_ok} {mode} calls succeeded).", file=sys.stderr)


if __name__ == "__main__":
    main()